<#
.SYNOPSIS
    Regenerates a talent tab flavor's talent rank spell table from wago.tools.

.DESCRIPTION
    Classic Era and The Burning Crusade Classic report spellID 0 for every talent, so Talents.lua looks up each
    talent's spells in TalentSpellsClassic.lua or TalentSpellsTBC.lua. This downloads the Talent and TalentTab DB2
    tables for one client build from wago.tools and rewrites that flavor's file.

.PARAMETER Flavor
    classic (Classic Era) or tbc (The Burning Crusade Classic).

.PARAMETER Build
    The client build, such as 1.15.9.70576. The Version column of the WoW install's .build.info lists each one.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("classic", "tbc")]
    [string]$Flavor,
    [Parameter(Mandatory = $true)]
    [string]$Build
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

$flavors = @{
    classic = @{ File = "TalentSpellsClassic.lua"; Flag = "IsClassicEra"; Name = "Classic Era" }
    tbc = @{ File = "TalentSpellsTBC.lua"; Flag = "IsTBC"; Name = "The Burning Crusade Classic" }
}
$target = $flavors[$Flavor]

# Comment headings only; the client supplies every name the page shows.
$classNames = @{
    1 = "Warrior"; 2 = "Paladin"; 3 = "Hunter"; 4 = "Rogue"; 5 = "Priest"; 7 = "Shaman"; 8 = "Mage"; 9 = "Warlock"; 11 = "Druid"
}

function Get-Db2Table($table) {
    $response = Invoke-WebRequest -UseBasicParsing "https://wago.tools/db2/$table/csv?build=$Build"
    $rows = @($response.Content | ConvertFrom-Csv)
    if ($rows.Count -eq 0) {
        throw "wago.tools returned no $table rows for build $Build."
    }
    return $rows
}

$tabs = @{}
foreach ($tab in Get-Db2Table "TalentTab") {
    $tabs[[int]$tab.ID] = $tab
}

# One entry per talent, in talent frame order: class, tab, tier, then column.
$talents = foreach ($talent in Get-Db2Table "Talent") {
    $ranks = New-Object System.Collections.Generic.List[int]
    for ($i = 0; $i -le 8; $i++) {
        $spellId = [int]$talent."SpellRank_$i"
        if ($spellId -eq 0) {
            break
        }
        $ranks.Add($spellId)
    }
    if ($ranks.Count -eq 0) {
        continue
    }
    $tab = $tabs[[int]$talent.TabID]
    [pscustomobject]@{
        Id = [int]$talent.ID
        ClassId = [int]$talent.ClassID
        TabOrder = if ($tab) { [int]$tab.OrderIndex } else { 99 }
        TabName = if ($tab) { $tab.Name_lang } else { "Tab $($talent.TabID)" }
        Tier = [int]$talent.TierID
        Column = [int]$talent.ColumnIndex
        Entry = "[$($talent.ID)] = { $($ranks -join ', ') },"
    }
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("local _, TwintopQOL = ...")
$lines.Add("")
$lines.Add("-- Generated by tools\Update-TalentRankSpells.ps1 from the $Build Talent table ($($target.Name)). Don't edit by hand.")
$lines.Add("if not TwintopQOL.$($target.Flag) then")
$lines.Add("    return")
$lines.Add("end")
$lines.Add("")
$lines.Add("-- Talent ID -> the spell each rank teaches, rank 1 first. The client reports spellID 0 for every talent.")
$lines.Add("TwintopQOL.TalentRankSpells = {")

$groups = $talents | Sort-Object ClassId, TabOrder, Tier, Column, Id | Group-Object ClassId, TabOrder
foreach ($group in $groups) {
    $first = $group.Group[0]
    $className = $classNames[$first.ClassId]
    if ($null -eq $className) {
        $className = "Class $($first.ClassId)"
    }
    $lines.Add("    -- $($className): $($first.TabName)")
    $line = "   "
    foreach ($talent in $group.Group) {
        if ($line.Length + 1 + $talent.Entry.Length -gt 120) {
            $lines.Add($line)
            $line = "   "
        }
        $line = "$line $($talent.Entry)"
    }
    $lines.Add($line)
}
$lines.Add("}")

$path = Join-Path $root $target.File
[System.IO.File]::WriteAllText($path, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Output ("Wrote {0} talents to {1}." -f @($talents).Count, $target.File)
